"""Self-repair: Claude diagnoses a failed/degraded Daily Impact run, fixes the code,
and (only if the offline self-tests pass) the fix is committed to main and a fresh
run is started.

Run by the `repair` job in .github/workflows/run-watchdog.yml after the watchdog
raises a repairable alert. Inputs (env): ISSUE (alert issue number), RUN_ID (the
failed run), GH_TOKEN (GitHub token for gh/git), ANTHROPIC_API_KEY (or the
CLAUDE_CODE_OAUTH_TOKEN fallback).

Guardrails (enforced here, not by the model):
  - Claude gets file tools, web search, and only two shell commands (the self-tests
    and a syntax check). It never sees GitHub credentials and can't push.
  - Only changes to *.py / *.json / *.md in the repo root or tools/ are kept;
    anything else (e.g. .github/) is discarded.
  - The fix is merged only if `python3 tools/selftest.py` passes.
  - At most MAX_PER_DAY automatic repairs per UTC day; after that the issue is
    left for the owner.
"""
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import claude_llm  # noqa: E402

REPO = os.environ.get('GITHUB_REPOSITORY', 'composit3zer0/Daily-Impact')
ISSUE = os.environ.get('ISSUE', '').strip()
RUN_ID = os.environ.get('RUN_ID', '').strip()
MAX_PER_DAY = 2
TAG = '[auto-repair]'
ALLOWED = re.compile(r'^(tools/)?[\w.-]+\.(py|json|md)$')
FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'


def sh(*cmd, check=True, cwd=ROOT):
    res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if check and res.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} failed: {res.stderr.strip()[-800:]}")
    return res.stdout


def comment(body):
    if ISSUE:
        sh('gh', 'issue', 'comment', ISSUE, '--repo', REPO, '--body', body + FOOTER, check=False)
    print(body)


def repairs_today():
    since = datetime.now(timezone.utc).strftime('%Y-%m-%dT00:00:00Z')
    out = sh('git', 'log', 'origin/main', f'--since={since}', f'--grep={TAG}', '--fixed-strings',
             '--format=%H', check=False)
    return len([l for l in out.splitlines() if l.strip()])


def gather_context():
    issue = sh('gh', 'issue', 'view', ISSUE, '--repo', REPO, '--json', 'title,body,comments',
               check=False) if ISSUE else ''
    log = sh('gh', 'run', 'view', RUN_ID, '--repo', REPO, '--log', check=False) if RUN_ID else ''
    keep = [l for l in log.splitlines()
            if not re.search(r'git config|safe\.directory|submodule foreach|Post job|punycode|extraheader', l)]
    return issue[-6000:], '\n'.join(keep[-250:])


PROMPT = """You are maintaining "The Daily Impact", a daily HTML briefing generated by GitHub Actions in
this repository (working directory = repo root). Today's run failed or published a degraded edition.
Diagnose the root cause and, if it can be fixed in code or config, fix it with the smallest change.

How it works: .github/workflows/daily-report.yml runs generate_report.py, which calls Claude through
claude_llm.py (headless Claude Code, subscription token) to write the briefing from the SYSTEM_PROMPT
secret, then essential_reading.py adds "Today's Essential Reading" (curated feeds in
reading_sources.json, article checks, Claude picks and summaries; editorial rules in reading_prompt.md).
tools/run_watchdog.py raised the alert below. tools/selftest.py holds offline tests.

Rules:
- You may edit only *.py, *.json and *.md files in the repo root or tools/. Never edit .github/,
  never touch secrets, never weaken or delete tests, never remove the article checks
  (14-day freshness, paywall, no-repeat) or the briefing completeness check.
- Keep the fix minimal and focused on the root cause. Use web search if you need current facts
  (e.g. a feed or site that moved).
- After editing, run `python3 tools/selftest.py` and make sure it passes. You may also run
  `python3 -m py_compile <file>`.
- If the cause needs the owner (expired/missing token, usage limit, billing, a secret, GitHub
  settings) or is a one-off outage, change nothing and say so in needs_owner.

ALERT ISSUE:
{issue}

FAILED RUN LOG (tail):
{log}
"""

SCHEMA = {
    "type": "object", "additionalProperties": False,
    "properties": {
        "diagnosis": {"type": "string", "description": "Root cause, citing the decisive log lines."},
        "fix_summary": {"type": "string", "description": "One line describing the change, or empty if none."},
        "needs_owner": {"type": "string", "description": "What the owner must do, or empty."},
    },
    "required": ["diagnosis", "fix_summary", "needs_owner"],
}


def main():
    sh('git', 'fetch', '-q', 'origin', 'main', check=False)   # public repo: no credential needed
    done = repairs_today()
    if done >= MAX_PER_DAY:
        comment(f'Self-repair skipped: {done} automatic repairs already made today (limit {MAX_PER_DAY}). '
                'Leaving this one for the owner.')
        return 0

    issue, log = gather_context()
    hidden = {k: os.environ.pop(k) for k in ('GH_TOKEN', 'GITHUB_TOKEN') if k in os.environ}
    try:
        report = claude_llm.ask(
            PROMPT.format(issue=issue, log=log), schema=SCHEMA, cwd=ROOT, timeout=1500, attempts=1,
            tools=('Read', 'Edit', 'Write', 'Glob', 'Grep', 'Bash', 'WebSearch', 'WebFetch'),
            allowed=('Read', 'Edit', 'Write', 'Glob', 'Grep', 'WebSearch', 'WebFetch',
                     'Bash(python3 tools/selftest.py)', 'Bash(python3 -m py_compile *)'),
            label='self-repair')
    except claude_llm.ClaudeError as e:
        comment(f'Self-repair could not run: `{e}`. Most likely the Claude credentials need attention '
                '(ANTHROPIC_API_KEY secret) or the monthly API credit ran out.')
        return 1
    finally:
        os.environ.update(hidden)

    diagnosis = report.get('diagnosis', '').strip()
    fix = report.get('fix_summary', '').strip()
    owner = report.get('needs_owner', '').strip()

    changed = [l[3:].strip() for l in sh('git', 'status', '--porcelain').splitlines() if l.strip()]
    rejected = [p for p in changed if not ALLOWED.match(p)]
    for p in rejected:                                   # discard anything outside the allowed files
        sh('git', 'checkout', '--', p, check=False)
        sh('git', 'clean', '-fdq', '--', p, check=False)
    kept = [p for p in changed if ALLOWED.match(p)]

    header = f'## Self-repair\n\n**Diagnosis:** {diagnosis}'
    if owner:
        header += f'\n\n**Needs the owner:** {owner}'
    if rejected:
        header += f"\n\nDiscarded changes outside the allowed files: {', '.join(rejected)}"
    if not kept:
        comment(header + '\n\nNo code change was made.')
        return 0

    tests = subprocess.run([sys.executable, 'tools/selftest.py'], cwd=ROOT, capture_output=True, text=True)
    if tests.returncode != 0:
        sh('git', 'checkout', '--', '.', check=False)
        sh('git', 'clean', '-fdq', check=False)
        comment(header + f"\n\nProposed fix ({fix}) was **not merged**: the self-tests failed.\n\n"
                f"```\n{tests.stdout[-3000:]}\n```")
        return 1

    diff = sh('git', 'diff', '--stat')
    sh('git', 'add', '--', *kept)
    sh('git', '-c', 'user.name=Claude (self-repair)', '-c', 'user.email=actions@github.com',
       'commit', '-q', '-m', f'{TAG} {fix or "Fix Daily Impact run"}',
       '-m', f'Diagnosis: {diagnosis}\n\nAlert: #{ISSUE}  Failed run: {RUN_ID}')
    remote = (os.environ.get('REPAIR_REMOTE')        # tests only: push somewhere harmless
              or f"https://x-access-token:{os.environ['GH_TOKEN']}@github.com/{REPO}.git")
    sh('git', 'pull', '-q', '--rebase', remote, 'main')
    sh('git', 'push', '-q', remote, 'HEAD:main')
    sha = sh('git', 'rev-parse', 'HEAD').strip()
    sh('gh', 'workflow', 'run', 'daily-report.yml', '--repo', REPO, '--ref', 'main', check=False)
    comment(header + f'\n\n**Fix merged:** {fix} ({REPO}@{sha[:7]})\n\n```\n{diff}```\n'
            'Self-tests passed. A fresh Daily Impact run has been started; the watchdog will close this '
            'issue if it comes out healthy.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
